import i18n from "../i18n";
import { shopCatalog, TRANSFER_LESSON, type OutfitId } from "../shop/catalog";
import { create } from "zustand";
import { persist, createJSONStorage } from "zustand/middleware";
import AsyncStorage from "@react-native-async-storage/async-storage";
import type { Language } from "../types/api";

/** Coins earned the first time a lesson is completed. */
export const LESSON_REWARD_COINS = 10;
export type { Language } from "../types/api";
export type Country = "US" | "MX" | "KE";
type State = {
  language: Language;
  /** False until the learner picks a language; the welcome screen cycles until then. */
  languageChosen: boolean;
  country: Country;
  stage: string;
  goal: string;
  comfort: number;
  confidence: number[];
  readAloud: boolean;
  simple: boolean;
  large: boolean;
  onboarded: boolean;
  coins: number;
  hearts: number;
  streak: number;
  completed: string[];
  purchases: string[];
  bonus: string[];
  // Server learner created from these answers (see src/api/learner.ts).
  learnerId: string | null;
  learnerKey: string | null;
  // Bonus lesson title -> server lesson id, for lessons generated by the API.
  bonusLessonIds: Record<string, string>;
  pendingBonus: string | null;
  equippedOutfit: OutfitId | null;
  equipOutfit: (id: OutfitId) => void;
  dismissBonus: () => void;
  adoptLearner: (learnerId: string, learnerKey: string) => void;
  set: (
    value: Partial<
      Omit<
        State,
        | "set"
        | "complete"
        | "buy"
        | "addBonus"
        | "equipOutfit"
        | "dismissBonus"
        | "adoptLearner"
      >
    >,
  ) => void;
  complete: (id: string) => void;
  buy: (id: string, price: number) => boolean;
  addBonus: (title: string) => void;
};
export const useApp = create<State>()(
  persist(
    (set, get) => ({
      language: "en",
      languageChosen: false,
      country: "US",
      stage: "First job",
      goal: "Save more",
      comfort: 0.4,
      confidence: [0.5, 0.5, 0.5, 0.5, 0.5],
      readAloud: false,
      simple: false,
      large: false,
      onboarded: false,
      coins: 0,
      hearts: 5,
      streak: 0,
      completed: [],
      purchases: [],
      bonus: [],
      pendingBonus: null,
      equippedOutfit: null,
      equipOutfit: (id) => {
        if (get().purchases.includes(id)) set({ equippedOutfit: id });
      },
      dismissBonus: () => set({ pendingBonus: null }),
      adoptLearner: (learnerId, learnerKey) =>
        // Bonus lessons belong to one server learner; another learner's ids
        // return 404, so a new learner starts without them.
        set((state) =>
          state.learnerId === learnerId
            ? { learnerKey }
            : { learnerId, learnerKey, bonus: [], bonusLessonIds: {} },
        ),
      learnerId: null,
      learnerKey: null,
      bonusLessonIds: {},
      set: (value) => {
        set(value);
        if (value.language) void i18n.changeLanguage(value.language);
      },
      complete: (id) => {
        if (!get().completed.includes(id))
          set((s) => ({
            completed: [...s.completed, id],
            coins: s.coins + LESSON_REWARD_COINS,
          }));
      },
      buy: (id, price) => {
        const state = get();
        const item = shopCatalog.find((candidate) => candidate.id === id);
        if (
          !item ||
          item.price !== price ||
          state.coins < price ||
          state.purchases.includes(id) ||
          (id === "transfer" && state.bonus.includes(TRANSFER_LESSON))
        )
          return false;
        set({
          coins: state.coins - price,
          purchases: [...state.purchases, id],
          hearts: id === "heart" ? state.hearts + 1 : state.hearts,
          bonus:
            id === "transfer" ? [...state.bonus, TRANSFER_LESSON] : state.bonus,
          pendingBonus:
            id === "transfer" ? TRANSFER_LESSON : state.pendingBonus,
        });
        return true;
      },
      addBonus: (title) => {
        if (!get().bonus.includes(title))
          set((s) => ({ bonus: [...s.bonus, title], pendingBonus: title }));
      },
    }),
    {
      name: "kompass-v1",
      storage: createJSONStorage(() => AsyncStorage),
      version: 3,
      migrate: (persisted) => {
        const state = persisted as Partial<State>;
        return {
          ...state,
          // Anyone who already used the app has been through language setup.
          languageChosen: state.languageChosen ?? true,
          // Earlier versions seeded demo progress; start this preview clean once.
          completed: [],
          coins: 0,
          streak: 0,
          hearts: 5,
          purchases: [],
          bonus: [],
          onboarded: false,
          pendingBonus: state.pendingBonus ?? null,
          equippedOutfit: state.equippedOutfit ?? null,
          language: ["en", "es", "sw"].includes(state.language ?? "")
            ? state.language
            : "en",
          country: ["US", "MX", "KE"].includes(state.country ?? "")
            ? state.country
            : "US",
          learnerId: null,
          learnerKey: null,
          bonusLessonIds: {},
        };
      },
    },
  ),
);
